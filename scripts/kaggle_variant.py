def patch_raptor2(nb: dict) -> None:
    """Drop the two Raptor arms that do not share their decoding — 4 arms become 2.

    Raptor is the heaviest stage by a wide margin — 62+62+62+42 forward passes of a
    CoAtNet at 384 px per study, against six windows for the DINO ensemble. The two arms
    scheduled singly on the second GPU each cost a full independent pass; the surviving
    pair runs together and shares its decoded windows.

    The scheduler addresses arms by the positions they held in the full list, in three
    places, so shortening the list breaks it three times. All three are rewritten to go
    by name.
    """

    cells = nb["cells"]
    _edit(cells, "ARMS = [", lambda s: s.replace(
        "ARMS = [",
        "# TRIMMED: the two arms scheduled singly, each a full independent pass. The\n"
        "# survivors share their decoded windows. `weights /= weights.sum()` renormalises\n"
        "# downstream and nothing asserts a count.\n"
        "_ARMS_DROP = ['native384dense-v10', 'native384-v8']\n"
        "ARMS = [", 1).replace(
        "\ndef build_backbone(",
        "\nARMS = [a for a in ARMS if a['name'] not in _ARMS_DROP]\n"
        "print('[trim] Raptor arms kept: ' + ', '.join(a['name'] for a in ARMS), flush=True)\n"
        "\n\ndef build_backbone(", 1), "trim:arms")

    _edit(cells, "first, reverse = arms[0], arms[2]", lambda s: s.replace(
        "        first, reverse = arms[0], arms[2]",
        f"        _pair = [a for a in arms if a['name'] in {SHARED_PAIR!r}]\n"
        "        _at = {a['name']: i for i, a in enumerate(arms)}\n"
        "        first, reverse = _pair[0], _pair[1]").replace(
        "outputs[0][study_index]", "outputs[_at[first['name']]][study_index]").replace(
        "outputs[2][study_index]", "outputs[_at[reverse['name']]][study_index]"),
        "trim:pair")

    _edit(cells, "run_single(1, torch.device('cuda:1'))", lambda s: s.replace(
        """    def gpu_one():
        with torch.cuda.device(1):
            run_single(1, torch.device('cuda:1'))
            run_single(3, torch.device('cuda:1'))""",
        "    def gpu_one():\n"
        "        with torch.cuda.device(1):\n"
        "            for _index, _arm in enumerate(arms):\n"
        f"                if _arm['name'] in {SHARED_PAIR!r}:\n"
        "                    continue\n"
        "                run_single(_index, torch.device('cuda:1'))"), "trim:scheduler")


def patch_nocoat(nb: dict) -> None:
    """Drop all four CoAtNet readers — 56.7 % of the pipeline's compute, worth +0.001.

    They are subprocesses, each reloading its own weights, and they run strictly one
    after another on any cohort over 48 studies — `RSNA_PARALLEL_COAT_READERS` defaults
    to off above that. With none of them `_members` stays empty and the code takes its
    own documented branch: "no CoAt family member available; public Raptor retained".
    """

    _edit(nb["cells"], "_run_residual_reader, _run_global96_reader", lambda s: s.replace(
        """    if _parallel_pairs:
        for _pair in ((_run_residual_reader, _run_d4_reader),
                      (_run_global96_reader, _run_repairv1_reader)):
            with _KeThreadPool(max_workers=2) as _pool:
                _jobs = [_pool.submit(_reader) for _reader in _pair]
                for _job in _jobs:
                    _job.result()
    else:
        for _reader in (_run_residual_reader, _run_global96_reader,
                        _run_d4_reader, _run_repairv1_reader):
            _reader()""",
        "    # TRIMMED: no CoAt reader runs; the empty-family branch keeps public Raptor.\n"
        "    print('[trim] CoAt readers skipped; public Raptor stands', flush=True)"),
        "coat")


#: How much of its column each expert takes from the host, as ranks. 0.5 is what was
