#: That host scored 0.835 internally; this one scores 0.943 on the leaderboard. A
#: stronger host deserves more weight, so 0.5 is probably too generous here — but tuning
#: it would mean fitting a constant on one submission, which is how a leaderboard teaches
#: you its noise. It is left where it was measured, and moved once there is a reading.
#:
#: For scale: the author's own graft of a foreign leg uses 0.45 across all twelve
#: columns. Ours is 0.5 across seven, which is less total mass, not more.
