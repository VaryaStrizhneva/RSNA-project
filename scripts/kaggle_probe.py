"""One expert, priced on the hidden test with no host at all.

    python -m scripts.kaggle_probe "PF OA" --push

**What this measures and why it needs its own notebook.** The void probes read the host's
AUC on one column by replacing that column with a constant: a constant ties every study,
an AUC counts tied pairs as half, so the column scores exactly 0.5 and the macro falls by
`(auc - 0.5) / 12`. The symmetric measurement for *our* expert is the same arithmetic run
the other way — our expert carries one column, every other column is the constant, and

    auc_ours = 12 * macro - 5.5

That is the only figure comparable to the host's. The out-of-fold numbers are agreement
with the label extractor on training studies, and the extractor itself only matches the
58 radiologist readings at 0.841; the 58 gold studies are the right quantity at the wrong
precision, ±0.05.

**Why no host.** Grafting this onto a host would run eight hours of someone else's
pipeline to produce twelve columns, of which eleven are then overwritten by a constant and
the twelfth by us. `_overwrite` at weight 1.0 takes our *ordering* and reassigns it the
values the column already held — a monotone remap, so the AUC is exactly ours and the
host's values never enter it. They matter for one thing only: the studies our expert
cannot read, which keep the host's rank. Here those studies take the constant instead, so
this reads our expert **alone** and reads it slightly pessimistically, which is the honest
direction for a measurement of our own work.

It also removes every dependency on the host's weights datasets — one of which Kaggle
currently refuses to submit against because it carries no version — and turns an
eight-hour run into a few minutes.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "src"))

from rsna.data.labels import TARGET_COLUMNS as TARGETS      # noqa: E402
from scripts.kaggle_variant import OWNER                    # noqa: E402

CELL = '''# ============ ONE EXPERT, PRICED ALONE ON THE HIDDEN TEST ============
# Generated by scripts/kaggle_probe.py. No host: the twelve columns start at a constant
# 0.5 and exactly one of them is then written by our expert.
#
# A constant column scores exactly 0.5 — every study ties, and an AUC counts a tied pair
# as half — so the submitted macro is
#
#     macro = (auc_ours + 11 * 0.5) / 12      and therefore    auc_ours = 12 * macro - 5.5
#
# which is the same arithmetic the void probes used on the host, run the other way. It is
# the only figure on the same footing as the host's: the out-of-fold numbers measure
# agreement with the label extractor, which itself scores 0.841 against the 58
# radiologist readings, and those 58 studies carry +/-0.05.
#
# Studies this expert cannot read keep the floor's own value rather than a host rank. The
# floor is an arbitrary ramp, so those studies are ordered arbitrarily against ours and
# contribute about 0.5 on the pairs they are in -- the same as a tie would, in
# expectation. For `PF OA` that is 64 studies of 4407, 1.5 %.
import os
import sys
import tempfile
import zipfile
from pathlib import Path

COLUMN = {column!r}
TARGETS = {targets!r}
INPUT = Path("/kaggle/input")


def _walk(root):
    for current, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in ("train_series", "test_series")]
        yield Path(current), dirs, files


def _find_library():
    for current, dirs, files in _walk(INPUT):
        if "config.py" in files and "infer" in dirs:
            return current
    for current, _, files in _walk(INPUT):
        for name in files:
            if name.endswith(".zip") and "rsna" in name:
                target = Path(tempfile.mkdtemp())
                with zipfile.ZipFile(current / name) as archive:
                    archive.extractall(target)
                for inner, inner_dirs, inner_files in os.walk(target):
                    if "config.py" in inner_files and "infer" in inner_dirs:
                        return Path(inner)
    return None


_runs = {{}}
for _current, _, _files in _walk(INPUT):
    if "fold0.pt" in _files and _current.name.startswith(("expert_", "landmark_")):
        _runs[_current.name] = _current
experts = sorted(p for n, p in _runs.items() if n.startswith("expert_"))
landmarks = sorted(p for n, p in _runs.items() if n.startswith("landmark_"))
library = _find_library()
root = next((str(c) for c, _, f in _walk(INPUT) if "test.csv" in f), None)
print(f"[probe] library={{library}} experts={{len(experts)}} landmarks={{len(landmarks)}} "
      f"root={{root}}", flush=True)
assert library and experts and landmarks and root, "a mount is missing"

import pandas as pd
import torch

staging = Path(tempfile.mkdtemp())
os.symlink(library, staging / "rsna")
sys.path.insert(0, str(staging))
from rsna.infer import run_expert_submission

# The floor every column starts from. Writing it here rather than taking a host's is the
# whole point: nothing of anyone else's model enters the number this notebook reports.
studies = pd.read_csv(Path(root) / "test.csv", dtype=str)["StudyInstanceUID"]
floor = pd.DataFrame({{"StudyInstanceUID": studies}})
for t in TARGETS:
    floor[t] = 0.5
# The tested column must NOT start constant. `_overwrite` writes `np.sort(host)[rank]` --
# our *ordering* reassigned onto the values the column already held -- so a constant floor
# would map our ordering onto a constant and destroy it: the column would stay at 0.5 and
# this notebook would report 0.5 whatever the expert does. Distinct values let the remap
# be monotone, which is what makes the reported AUC exactly ours.
import numpy as np
floor[COLUMN] = np.linspace(0.0, 1.0, len(floor))
floor.to_csv("submission.csv", index=False)
print(f"[probe] floor written: {{len(floor)}} studies, {{len(TARGETS) - 1}} columns at 0.5 "
      f"and {{COLUMN}} on a distinct ramp so the remap stays monotone", flush=True)

run_expert_submission(
    expert_runs=experts, landmark_runs=landmarks, package=None,
    data_root=root, split="test_series", out="submission.csv",
    scratch="/kaggle/working/roi" if Path("/kaggle/working").is_dir() else None,
    blend={{COLUMN: 1.0}}, workers=4, mirror_tta=False, jitter_tta=False,
    device="cuda" if torch.cuda.is_available() else "cpu", log=print)

done = pd.read_csv("submission.csv")
moved = [c for c in done.columns[1:] if done[c].nunique() > 1]
print(f"[probe] columns no longer constant: {{moved}}", flush=True)
assert moved == [COLUMN], f"expected only {{COLUMN}} to move, got {{moved}}"
print(f"[probe] auc_ours = 12 * macro - 5.5", flush=True)
'''


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("column", help="one of the twelve targets")
    ap.add_argument("--experts", default="rsna-knee-experts-bundle5")
    ap.add_argument("--slug", default=None)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--push", action="store_true")
    args = ap.parse_args()

    if args.column not in TARGETS:
        raise SystemExit(f"{args.column!r} is not one of {TARGETS}")
    tag = (args.column.lower().replace(" ", "").replace("'", "")
           .replace("meniscus", "men").replace("lateral", "lat")
           .replace("medial", "med"))
    slug = args.slug or f"rsna-knee-only-{tag}"
    out = args.out or Path("/tmp") / slug
    out.mkdir(parents=True, exist_ok=True)

    nb = {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {},
                     "outputs": [],
                     "source": [CELL.format(column=args.column, targets=TARGETS)]}],
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                      "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 5}
    (out / "notebook.ipynb").write_text(json.dumps(nb, indent=1) + "\n")
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{OWNER}/{slug}",
        "title": slug.replace("rsna-knee-", "RSNA Knee ").replace("-", " "),
        "code_file": "notebook.ipynb", "language": "python",
        "kernel_type": "notebook", "is_private": True,
        "enable_gpu": True, "enable_internet": False,
        "dataset_sources": [f"{OWNER}/rsna-src", f"{OWNER}/{args.experts}"],
        "competition_sources": ["rsna-knee-abnormality-detection"],
        "kernel_sources": [], "model_sources": [],
    }, indent=2) + "\n")
    print(f"{slug}: {args.column} by our expert, the other {len(TARGETS) - 1} at 0.5")
    print(f"  mounts: rsna-src + {args.experts} + the competition — no host")
    print(f"  reads: auc_ours = 12 * macro - 5.5")
    print(f"  -> {out}")
    if args.push:
        subprocess.run([sys.executable, "-m", "scripts.kaggle_push",
                        "--kernel-dir", str(out)], check=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
